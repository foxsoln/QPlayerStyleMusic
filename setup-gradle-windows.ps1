#requires -Version 5.1
<#
Downloads the official Gradle distribution into this project (not a Java SDK),
then runs Gradle's official `wrapper` task. The resulting gradlew.bat and wrapper
jar are generated by Gradle itself. Requires internet, Android SDK, and JDK 21.
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$version = '9.3.1'
$toolDir = Join-Path $root '.gradle-bootstrap'
$zipPath = Join-Path $toolDir "gradle-$version-bin.zip"
$gradleBat = Join-Path $toolDir "gradle-$version\bin\gradle.bat"
New-Item -ItemType Directory -Force $toolDir | Out-Null
if (-not (Test-Path $gradleBat)) {
    Write-Host 'Downloading official Gradle distribution...' -ForegroundColor Cyan
    $source = "https://services.gradle.org/distributions/gradle-$version-bin.zip"
    Invoke-WebRequest -Uri $source -OutFile $zipPath -UseBasicParsing
    Expand-Archive -Path $zipPath -DestinationPath $toolDir -Force
}
Push-Location $root
try {
    & $gradleBat wrapper --gradle-version $version --distribution-type bin
    if ($LASTEXITCODE -ne 0) { throw "Gradle wrapper task failed: $LASTEXITCODE" }
    Write-Host 'Gradle wrapper generated. Open this folder in Android Studio.' -ForegroundColor Green
    Write-Host 'To build an APK, run: .\gradlew.bat :app:assembleDebug'
} finally {
    Pop-Location
}
