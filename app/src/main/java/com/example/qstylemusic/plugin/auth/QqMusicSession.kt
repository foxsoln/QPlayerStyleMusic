package com.example.qstylemusic.plugin.auth

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import org.json.JSONObject
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * QQ Music credentials belong to the native host, never to a .mplug script.
 * Sessions are accepted after successful QQ Music OAuth QR exchange or the legacy validated official WebView login.
 * AES-GCM IVs are generated by Android Keystore; no caller-provided IV on encrypt.
 */
class QqMusicSession(context: Context) {
    private val prefs = context.applicationContext.getSharedPreferences(
        "qstyle_qqmusic_session_v1", Context.MODE_PRIVATE
    )

    data class Credentials(val uin: String, val cookies: Map<String, String>) {
        val musicKey: String get() = cookies["qm_keyst"]
            ?: cookies["qqmusic_key"]
            ?: cookies["qqmusic_key_ext"]
            ?: ""

        fun cookieHeader(): String = cookies.entries.joinToString("; ") { (k, v) -> "$k=$v" }
    }

    val hasLocalSession: Boolean get() = read() != null

    /**
     * Persist only a completed QQ Music OAuth exchange. A QQ web login cookie by
     * itself must never count as a playback credential.
     */
    fun saveFromQrExchange(
        musicId: String,
        musicKey: String,
        rawCookies: Map<String, String> = emptyMap()
    ): Credentials {
        require(musicId.matches(Regex("[0-9]{4,20}"))) { "QQ 音乐 musicid 不合法" }
        require(musicKey.length in 12..8192 && !musicKey.contains('\n') &&
            !musicKey.contains('\r')) { "QQ 音乐 musickey 不合法" }
        val cookies = linkedMapOf<String, String>()
        rawCookies.forEach { (key, value) ->
            if (key in ACCEPTED && value.length in 1..8192 &&
                '\r' !in value && '\n' !in value) cookies[key] = value
        }
        // The QQ Music exchange credential is authoritative over earlier web tokens.
        cookies["uin"] = musicId
        cookies["qqmusic_uin"] = musicId
        cookies["musicid"] = musicId
        cookies["qm_keyst"] = musicKey
        cookies["qqmusic_key"] = musicKey
        cookies["login_type"] = "1"
        val credentials = Credentials(musicId, cookies)
        persist(credentials)
        return credentials
    }

    private fun persist(credentials: Credentials) {
        val body = JSONObject().put("uin", credentials.uin)
            .put("cookies", JSONObject(credentials.cookies as Map<*, *>))
            .toString().toByteArray(Charsets.UTF_8)
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, getKey())
        val iv = requireNotNull(cipher.iv)
        require(iv.size == 12)
        val encoded = Base64.encodeToString(iv + cipher.doFinal(body), Base64.NO_WRAP)
        prefs.edit().putString("ciphertext", encoded).apply()
    }

    fun clear() {
        prefs.edit().remove("ciphertext").apply()
    }

    /** Only capture the session after the website has completed user authorization. */
    fun saveFromOfficialWebView(cookieHeaders: Collection<String>): Credentials {
        val collected = linkedMapOf<String, String>()
        for (header in cookieHeaders) {
            for (part in header.split(';')) {
                val sep = part.indexOf('=')
                if (sep <= 0) continue
                val key = part.substring(0, sep).trim()
                val value = part.substring(sep + 1).trim()
                if (key in ACCEPTED && value.isNotBlank() && value.length <= 8192 &&
                    !value.contains('\n') && !value.contains('\r')) {
                    collected[key] = value
                }
            }
        }
        val rawUin = collected["uin"] ?: collected["qqmusic_uin"] ?: collected["wxuin"].orEmpty()
        val uin = rawUin.removePrefix("o").trim()
        require(uin.matches(Regex("[0-9]{4,20}"))) {
            "尚未检测到完整的 QQ 音乐登录身份，请先在官网完成扫码并确认"
        }
        val credentials = Credentials(uin, collected)
        require(credentials.musicKey.isNotBlank()) {
            "已发现 QQ 身份，但没有 QQ 音乐访问票据；请等待官网登录完成后再点校验"
        }
        persist(credentials)
        return credentials
    }

    fun read(): Credentials? = runCatching {
        val encoded = prefs.getString("ciphertext", null) ?: return null
        val raw = Base64.decode(encoded, Base64.NO_WRAP)
        require(raw.size > 28)
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.DECRYPT_MODE, getKey(), GCMParameterSpec(128, raw.copyOfRange(0, 12)))
        val json = JSONObject(String(cipher.doFinal(raw.copyOfRange(12, raw.size)), Charsets.UTF_8))
        val uin = json.getString("uin")
        val cookieObject = json.getJSONObject("cookies")
        val cookies = cookieObject.keys().asSequence().associateWith { cookieObject.getString(it) }
        Credentials(uin, cookies).takeIf { it.musicKey.isNotBlank() }
    }.getOrNull()

    private fun getKey(): SecretKey {
        val store = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        (store.getKey(KEY_ALIAS, null) as? SecretKey)?.let { return it }
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore")
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            ).setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .build()
        )
        return generator.generateKey()
    }

    private companion object {
        const val KEY_ALIAS = "qstyle_qqmusic_cookie_aes_v1"
        val ACCEPTED = setOf(
            "uin", "qqmusic_uin", "wxuin", "qqmusic_key", "qqmusic_key_ext",
            "qm_keyst", "skey", "p_skey", "psrf_qqaccess_token", "login_type",
            "euin", "wxunionid", "wxopenid", "musicid"
        )
    }
}
